"""Regenerate evals/report.md from every saved result file (newest first)."""

from __future__ import annotations

import json

from claimpilot.config import EVALS_DIR

TARGETS = (
    "Targets (requirements §1): decision accuracy ≥ 80%, safe-escalation recall ≥ 95%, "
    "citation correctness ≥ 90%."
)


def _pct(v: float | None) -> str:
    return "—" if v is None else f"{v * 100:.0f}%"


def _coverage_row(r: dict) -> str:
    s = r["summary"]
    return (
        f"| {r['timestamp'][:16]} | {r['suite']} | {r['model']} "
        f"| {r.get('prompt_version', 'v1')} | {r['llm_mode']} | {s['n']} "
        f"| {_pct(s['decision_accuracy'])} | {_pct(s['escalation_recall'])} "
        f"| {s['false_auto_approvals']} | {_pct(s['citation_correctness'])} "
        f"| {s['latency_p50_ms'] or '—'} | {s['avg_input_tokens'] or '—'}/"
        f"{s['avg_output_tokens'] or '—'} | {s['errors']} |"
    )


def _severity_row(r: dict) -> str:
    s = r["summary"]
    return (
        f"| {r['timestamp'][:16]} | {r['suite'].removeprefix('severity').strip('_') or 'test'} "
        f"| {r['model']} "
        f"| {r.get('prompt_version', 'v1')} | {r['llm_mode']} | {s['n']} "
        f"| {_pct(s['accuracy'])} | {_pct(s['within_one'])} | {_pct(s['high_recall'])} "
        f"| {s['latency_p50_ms'] or '—'} | {s['errors']} |"
    )


def _letters_row(r: dict) -> str:
    s = r["summary"]
    return (
        f"| {r['timestamp'][:16]} | {r['model']} | {r['llm_mode']} | {s['n']} "
        f"| {_pct(s['decision'])} | {_pct(s['amount'])} | {_pct(s['no_leak'])} "
        f"| {_pct(s['deductible_wording'])} | {_pct(s['flagged_for_edit'])} "
        f"| {_pct(s['sendable_all_checks'])} | {s['avg_revisions']} | {s['errors']} |"
    )


def write_report() -> None:
    results = [
        json.loads(p.read_text())
        for p in sorted((EVALS_DIR / "results").glob("*.json"), reverse=True)
    ]
    coverage = [_coverage_row(r) for r in results if r["suite"].startswith("coverage")]
    severity = [_severity_row(r) for r in results if r["suite"].startswith("severity")]
    letters = [_letters_row(r) for r in results if r["suite"] == "letters"]
    (EVALS_DIR / "report.md").write_text(
        "# Eval report\n\n"
        "Generated by `claimpilot.evals`; do not edit by hand. "
        "Raw results are in `evals/results/`.\n"
        "Runs in `fake` mode only check the wiring; their numbers mean nothing.\n\n"
        f"## Coverage (FR-2)\n\n{TARGETS}\n\n"
        "| Run (UTC) | Suite | Model | Prompt | Mode | N | Decision acc. | Escalation recall "
        "| False auto-approvals | Citation correct | p50 ms | Tokens in/out | Errors |\n"
        "|---|---|---|---|---|---|---|---|---|---|---|---|---|\n"
        + ("\n".join(coverage) or "| — |" + " |" * 12)
        + "\n\n## Photo severity (FR-1.5)\n\n"
        "Claim-style damage photos (CC BY / BY-SA / CC0, see data/photos/ATTRIBUTION.md), "
        "hand-labeled. `dev` was used to write the rubric; `val` only checks it. "
        "No target set in requirements; reported honestly.\n\n"
        "| Run (UTC) | Set | Model | Prompt | Mode | N | Exact | Within one level | High recall "
        "| p50 ms | Errors |\n|---|---|---|---|---|---|---|---|---|---|---|\n"
        + ("\n".join(severity) or "| — |" + " |" * 10)
        + "\n\n## Decision letters (FR-6)\n\n"
        "Target: decision and amount match the record in 100% of letters. Flagged letters go "
        "to an adjuster and are not sent; every sendable letter must pass all checks.\n\n"
        "| Run (UTC) | Model | Mode | N | Decision | Amount | No internal leak "
        "| Deductible wording | Flagged for edit | Sendable: all checks | Avg revisions "
        "| Errors |\n|---|---|---|---|---|---|---|---|---|---|---|---|\n"
        + ("\n".join(letters) or "| — |" + " |" * 11)
        + "\n"
    )
